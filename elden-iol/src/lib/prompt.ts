export function buildExtractionPrompt(): string {
  return `你正在讀取一張眼科生物量測儀（biometry）報告單的照片，
最常見的是 ZEISS IOLMaster 700 的「IOL calculation」報告單。
請把上面的數值抽取成結構化資料，供人工水晶體度數計算使用。

這是醫療資料，讀錯會導致病患被植入錯誤的人工水晶體，因此：

1. **看不清楚的欄位，value 一律填 null，絕對不要猜測、不要推算、不要用常見值代替。**
   信心值 (confidence) 誠實反映你的把握程度。

2. **rawText 必須逐字記錄你在圖上看到的原始文字**（含單位與符號），
   例如 "24.49 mm (!)"、"43.08 D"、"---"。這是給人工比對用的，不要美化或正規化。

3. **borderline 欄位**：報告單會在數值旁印一個 (!) 驚嘆號標記，代表該量測值處於臨界範圍。
   看到 (!) 就把該欄位的 borderline 設為 true。

4. **warnings 陣列必須抓取報告單上所有的文字警告**，
   通常印在頁面最上方、旁邊有一個大驚嘆號圖示，
   例如 "OD: Axial length measurements slightly inconsistent. Please check fixation."
   逐字照抄英文原文。沒有警告就給空陣列。這個欄位絕對不能省略。

5. **版面**：報告單左半邊是 OD（右眼），右半邊是 OS（左眼）。
   若某一眼的狀態 (LS) 是 Pseudophakic（已植入人工水晶體），
   該眼通常整欄都是 --- 沒有數值，此時 hasData 設為 false，各欄位 value 填 null。

6. **這張圖是用手機翻拍紙本報告單，不是掃描檔。** 因此必然會有以下狀況，請據此判讀：
   - **反光**：閃光燈或天花板燈管在紙面上造成白色光斑，可能整片蓋掉一個數字。
   - **傾斜與變形**：拍攝角度造成梯形變形，直線不直、字往一邊縮。
   - **裁切**：邊緣的欄位可能被裁掉一部分或整個不在畫面內。
   - **對焦與手震**：部分區域模糊到只能看出「有幾位數」而看不出是哪個數字。
   只要一個數值被反光遮住、被裁掉、或模糊到無法逐字確認，
   **該欄位就填 null**。不要用同一眼的其他數值推算，不要用左右眼互相推補，
   不要因為「看起來應該是 24.xx」就補上去。少一個值使用者會自己補打，
   補錯一個值可能沒有人發現。

7. **可能不是 IOLMaster 700。** 診所會有其他機型的生物量測儀，版面配置不同，
   但欄位標籤（AL、ACD、LT、WTW、K1、K2、TK1、TK2 等）大同小異。
   **請依欄位標籤的語意抓取，不要依賴數值在畫面上的固定位置。**
   標籤與數值的對應關係看不清楚時，同樣填 null。

8. **同一個欄位出現多個候選數值時，不要自己挑。**
   不同機型會把同一個量測值印成好幾組，例如：
   - NIDEK AL-Scan 的 AL 與 ACD 同時有 Optical 與 Ultrasound 兩組，
     報告單上會有一行「Select: AL (Optical), ACD (Ultrasound)」之類的標示，
     **依那行標示取對應的那一組**。
   - NIDEK 的角膜屈光度分 KM φ2.4mm 與 KM φ3.3mm 兩區，
     **一律優先取 φ2.4mm 那一組**（診所醫師指定）。R1 為一個主徑線、R2 為另一個，
     各自帶自己的軸位；把它們當成 K1 / K2 回報。
   - OCULUS Pentacam 的 ACD 標為「ACD (Ext.)」，K 值標為「SimK」。

   **如果報告單上沒有標示、或你判斷不出該用哪一組，該欄位一律填 null，
   並在 warnings 裡寫明「哪個欄位有幾個候選值、分別是多少」。**
   醫師寧可自己補一格，也不要收到一個看起來很合理但選錯來源的數字。

9. **欄位對照**：
   - AL = 眼軸長 (mm)
   - ACD = 前房深度 (mm)
   - LT = 水晶體厚度 (mm)
   - WTW = 角膜橫徑 (mm)
   - K1 / K2 = 角膜前表面兩主徑線屈光度 (D)，各自帶一個軸位 (度)
   - TK1 / TK2 = Total K，含角膜後表面的量測值 (D)，各自帶軸位
   - targetRefraction = Target ref. 目標屈光度 (D)
   - lensModel = 計算所用的人工水晶體型號字串，逐字照抄（例如 "AMO Tecnic 1 ZCB00-1"）
   - aConstant = 該型號的 A const. 數值

10. 軸位一律以度為單位的整數（0–180）。度數一律保留報告單上的小數位數。

11. overallConfidence 反映你對整張報告單判讀的整體把握程度。
    照片有大面積反光、嚴重變形或關鍵欄位被裁掉時，這個值就要明顯下降。

12. device：確認是 IOLMaster 700 就填 "IOLMaster700"，其他機型一律填 "unknown"。
    deviceRawText 則**逐字記錄報告單上印的儀器名稱或型號字樣**
    （例如 "IOLMaster 700"、"LENSTAR LS 900"、"ARGOS"），讀不到就填 null。
    這是用來讓我們知道實際遇到哪些機型，即使 device 判為 unknown 也要盡量填。
    reportDate 取報告單上的 "Report dated" 日期，格式 YYYY-MM-DD；讀不到就填 null。

13. **不要抽取病患姓名與病歷號。** 即使圖上看得到（包含技術員手寫的），
    也不要放進任何欄位、不要寫進 rawText、不要寫進 warnings。
    這份資料不儲存病患個資。`;
}
